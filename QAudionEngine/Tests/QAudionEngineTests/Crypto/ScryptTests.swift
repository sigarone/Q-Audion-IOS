import XCTest
@testable import QAudionEngine

final class ScryptTests: XCTestCase {

    /// RFC 7914 Test Vector 1: scrypt("", "", N=16, r=1, p=1, dkLen=64)
    func test_rfc7914_vector1() throws {
        let key = try Scrypt.deriveKey(password: Data(), salt: Data(),
                                       n: 16, r: 1, p: 1, dkLen: 64)
        let expected: [UInt8] = [
            0x77, 0xd6, 0x57, 0x62, 0x38, 0x65, 0x7b, 0x20, 0x3b, 0x19, 0xca, 0x42, 0xc1, 0x8a, 0x04, 0x97,
            0xf1, 0x6b, 0x48, 0x44, 0xe3, 0x07, 0x4a, 0xe8, 0xdf, 0xdf, 0xfa, 0x3f, 0xed, 0xe2, 0x14, 0x42,
            0xfc, 0xd0, 0x06, 0x9d, 0xed, 0x09, 0x48, 0xf8, 0x32, 0x6a, 0x75, 0x3a, 0x0f, 0xc8, 0x1f, 0x17,
            0xe8, 0xd3, 0xe0, 0xfb, 0x2e, 0x0d, 0x36, 0x28, 0xcf, 0x35, 0xe2, 0x0c, 0x38, 0xd1, 0x89, 0x06
        ]
        XCTAssertEqual(Array(key), expected)
    }

    /// RFC 7914 Test Vector 2: scrypt("password", "NaCl", N=1024, r=8, p=16, dkLen=64)
    /// SLOW — skip in routine CI.
    func test_rfc7914_vector2_slow() throws {
        try XCTSkipIf(ProcessInfo.processInfo.environment["FAST_TESTS"] == "1",
                      "Slow scrypt KAT — set FAST_TESTS=0 to run")

        let key = try Scrypt.deriveKey(
            password: Data("password".utf8),
            salt: Data("NaCl".utf8),
            n: 1024, r: 8, p: 16, dkLen: 64
        )
        let expected: [UInt8] = [
            0xfd, 0xba, 0xbe, 0x1c, 0x9d, 0x34, 0x72, 0x00, 0x78, 0x56, 0xe7, 0x19, 0x0d, 0x01, 0xe9, 0xfe,
            0x7c, 0x6a, 0xd7, 0xcb, 0xc8, 0x23, 0x78, 0x30, 0xe7, 0x73, 0x76, 0x63, 0x4b, 0x37, 0x31, 0x62,
            0x2e, 0xaf, 0x30, 0xd9, 0x2e, 0x22, 0xa3, 0x88, 0x6f, 0xf1, 0x09, 0x27, 0x9d, 0x98, 0x30, 0xda,
            0xc7, 0x27, 0xaf, 0xb9, 0x4a, 0x83, 0xee, 0x6d, 0x83, 0x60, 0xcb, 0xdf, 0xa2, 0xcc, 0x06, 0x40
        ]
        XCTAssertEqual(Array(key), expected)
    }

    func test_invalidN_throws() {
        XCTAssertThrowsError(try Scrypt.deriveKey(password: Data(), salt: Data(), n: 3, r: 1, p: 1, dkLen: 32))
    }

    func test_invalidR_throws() {
        XCTAssertThrowsError(try Scrypt.deriveKey(password: Data(), salt: Data(), n: 16, r: 0, p: 1, dkLen: 32))
    }
}
