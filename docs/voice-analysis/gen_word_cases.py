#!/usr/bin/env python3
"""Builds voice-word-cases.tsv: the conformance table of section 12.6 (the voice word
of the tone row) of docs/voice-analysis-spec.md.

Usage: python3 docs/voice-analysis/gen_word_cases.py out.tsv

Each case is a sequence of analysis steps, one character per step:
  V  a result with voiced = true
  u  a result with voiced = false
  R  a reset or a long gap (section 2): no result, the history is cleared
and the expected word after every result, one character per V or u:
  v  "voce"   s  "silenzio"   -  no word
"""
import sys

SILENCE_STEPS = 20  # 2.0 s of audio time (HOP = 100 ms)


def words(steps):
    out = []
    heard = False      # a voiced result since the last reset
    unvoiced = 0       # consecutive unvoiced results since the last voiced one or the reset
    for c in steps:
        if c == "R":
            heard, unvoiced = False, 0
            continue
        if c == "V":
            heard, unvoiced = True, 0
        elif c == "u":
            unvoiced += 1
        else:
            raise ValueError(c)
        if unvoiced >= SILENCE_STEPS:
            out.append("s")
        elif heard:
            out.append("v")
        else:
            out.append("-")
    return "".join(out)


def seq(*parts):
    return "".join(ch * n for ch, n in parts)


CASES = [
    ("start_no_voice", "no voice from the start: no word for 19 steps, silence from the 20th",
     seq(("u", 25))),
    ("first_voice", "voice after half a second of nothing: the word appears with the voice",
     seq(("u", 5), ("V", 1), ("u", 3))),
    ("short_pause", "a 1.5 s pause inside speech keeps the voice word",
     seq(("V", 5), ("u", 15), ("V", 3))),
    ("pause_19", "19 unvoiced steps (1.9 s): still voice",
     seq(("V", 3), ("u", 19), ("V", 1))),
    ("pause_20", "20 unvoiced steps (2.0 s): silence on the 20th, voice again on the next voiced step",
     seq(("V", 3), ("u", 20), ("V", 2))),
    ("long_silence", "the other person stops talking for 3 s",
     seq(("V", 2), ("u", 30))),
    ("speech_pattern", "running speech: short voiced runs and gaps of 1 to 6 steps never show silence",
     seq(("V", 2), ("u", 1), ("V", 3), ("u", 4), ("V", 1), ("u", 6), ("V", 4), ("u", 2), ("V", 1))),
    ("single_voiced_in_silence", "one voiced step inside a long silence: voice for that step and the 19 after",
     seq(("u", 25), ("V", 1), ("u", 25))),
    ("reset_clears", "a reset forgets the voice: no word again until voice or 2 s",
     seq(("V", 3), ("R", 1), ("u", 21))),
    ("reset_in_silence", "a reset during silence: the count starts again",
     seq(("V", 1), ("u", 22), ("R", 1), ("u", 3), ("V", 1))),
]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    lines = ["# voice-word-cases.tsv: section 12.6 of docs/voice-analysis-spec.md. Generated by gen_word_cases.py; do not edit.",
             "name\tsteps\texpected\tdescription"]
    for name, desc, steps in CASES:
        lines.append("\t".join([name, steps, words(steps), desc]))
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
